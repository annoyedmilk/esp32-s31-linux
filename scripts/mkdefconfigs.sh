#!/bin/sh
# SPDX-License-Identifier: MIT
# Make br2-external/configs/<board>_defconfig from the common fragment, the
# fragment of the root (flashroot or diskroot), and the fragment of the
# board, in br2-external/board/esp32s31/defconfig/, with merge_config.sh of
# Buildroot.  A setting must be in one fragment only.
# With --check, change nothing, and fail when a defconfig differs from its
# fragments.
#
#   scripts/mkdefconfigs.sh [--check]
#
# merge_config.sh needs GNU sed and coreutils: run this on Linux or in the
# build container (make defconfigs).
set -eu

cd "$(dirname "$0")/.."
frag=br2-external/board/esp32s31/defconfig
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
status=0

for board in korvo1 esp32s31 coreboard1; do
	case $board in
	esp32s31) fragments="common flashroot $board" ;;
	*) fragments="common diskroot $board" ;;
	esac
	CONFIG_=BR2_ external/buildroot/support/kconfig/merge_config.sh -m -O "$tmp" \
		$(for f in $fragments; do echo "$frag/$f.fragment"; done) >"$tmp/log" 2>&1 ||
		{ cat "$tmp/log" >&2; exit 1; }
	if grep -q 'is redefined' "$tmp/log"; then
		grep -A2 'is redefined' "$tmp/log" >&2
		echo "$board: a setting is in two fragments" >&2
		exit 1
	fi
	{
		echo "# Generated by scripts/mkdefconfigs.sh.  Do not edit: change"
		echo "# $(echo $fragments | sed 's/ /.fragment, /g; s/\(.*\), /\1 and /').fragment in $frag/."
		cat "$tmp/.config"
	} >"$tmp/$board"
	out=br2-external/configs/${board}_defconfig
	if [ "${1:-}" = --check ]; then
		cmp -s "$tmp/$board" "$out" ||
			{ echo "$out differs from its fragments: run make defconfigs" >&2; status=1; }
	else
		cp "$tmp/$board" "$out"
	fi
done
exit $status
