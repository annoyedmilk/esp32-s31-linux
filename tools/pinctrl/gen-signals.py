"""Write signals.c from gpio_sig_map.h of ESP-IDF.

    gen-signals.py gpio_sig_map.h COMMIT > signals.c

An index can have an input name (_IN_IDX), an output name (_OUT_IDX) and
names without a direction (_IDX).  A name without a direction goes to both
lists; the header does not tell its direction.  Aliases are skipped.
"""

import re
import sys

NSIGS = 256


def parse(path: str) -> tuple[list[list[str]], list[list[str]]]:
    ins: list[list[str]] = [[] for _ in range(NSIGS)]
    outs: list[list[str]] = [[] for _ in range(NSIGS)]
    with open(path) as f:
        for line in f:
            m = re.match(r"#define\s+(\w+)_IDX\s+(\d+)\s*$", line)
            if not m or int(m.group(2)) >= NSIGS:
                continue
            name, idx = m.group(1), int(m.group(2))
            if name in ins[idx] or name in outs[idx]:
                continue
            if name.endswith("_IN"):
                ins[idx].append(name)
            elif name.endswith("_OUT"):
                outs[idx].append(name)
            else:
                ins[idx].append(name)
                outs[idx].append(name)
    return ins, outs


def table(var: str, names: list[list[str]]) -> str:
    rows = [f'\t[{i}] = "{"/".join(n)}",' for i, n in enumerate(names) if n]
    return f"const char *const {var}[NSIGS] = {{\n" + "\n".join(rows) + "\n};\n"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    ins, outs = parse(sys.argv[1])
    print("/* SPDX-License-Identifier: MIT */")
    print(
        f"/* Generated by gen-signals.py from gpio_sig_map.h of ESP-IDF {sys.argv[2]}. */"
    )
    print()
    print('#include "esp32s31.h"')
    print()
    print(table("sig_in_names", ins))
    print(table("sig_out_names", outs), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
